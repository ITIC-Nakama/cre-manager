-- Messagerie conseiller <-> etudiant : UN fil par etudiant, partage par toute l'equipe CRE (conseillers et admins).
-- Aucune donnee a reprendre : les messages envoyes jusqu'ici (POST /dashboard/students/{id}/notify) n'etaient pas
-- enregistres.

CREATE TABLE conversations (
    id uuid PRIMARY KEY,
    student_id uuid NOT NULL UNIQUE REFERENCES students(user_id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_message_at timestamptz NOT NULL DEFAULT now(),
    -- Dernier message de chaque cote : les non-lus se calculent sans parcourir les messages.
    last_student_message_id bigint,
    last_staff_message_id bigint
);
CREATE INDEX idx_conversations_last_message_at ON conversations (last_message_at DESC);

CREATE TABLE conversation_messages (
    -- Identifiant croissant : ordre des messages et « lu jusqu'au message n », sans dependre de l'horloge.
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id uuid NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    -- Compte supprime : le message reste, signe « Ancien conseiller ».
    author_id uuid REFERENCES users(id) ON DELETE SET NULL,
    from_student boolean NOT NULL,
    body varchar(4000) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_conversation_messages_conversation ON conversation_messages (conversation_id, id);
CREATE INDEX idx_conversation_messages_author ON conversation_messages (author_id);

-- Derniere lecture par personne et par fil (« lu jusqu'au message n ») : sert a calculer les non-lus.
CREATE TABLE conversation_reads (
    conversation_id uuid NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    last_read_message_id bigint NOT NULL,
    read_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (conversation_id, user_id)
);
CREATE INDEX idx_conversation_reads_user ON conversation_reads (user_id);
